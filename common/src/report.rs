//! Єдиний канал, яким ядро щось повідомляє. Саме ядро нічого не друкує:
//! термінал і графічний інтерфейс показують повідомлення кожен по-своєму.

pub trait Reporter: Send {
    /// Хід роботи, частина основного результату.
    fn info(&self, text: &str);

    /// Попередження в основному результаті.
    fn warn(&self, text: &str);

    /// Побічне попередження під час запитів; не є частиною результату.
    fn diagnostic(&self, text: &str);

    /// Сирий вивід сторонньої програми або службовий текст, без обробки.
    fn log(&self, text: &str);

    /// Зараз буде запущено команду. `side` — побічна (оновлення метаданих).
    fn command(&self, line: &str, side: bool);

    /// Команда завершилась невдало.
    fn failure(&self, problem: &str);

    /// `true`, якщо термінала немає: вивід сторонніх програм треба передавати
    /// в `log`, а запитання від них залишаться без відповіді.
    fn captures_output(&self) -> bool {
        false
    }
}
